import { z } from 'zod';
import { SafeIdSchema } from './safeId';

export const MAP_TILE_SIZE = 32;
export const MAP_WORLD_WIDTH = 544;
export const MAP_COLUMNS = MAP_WORLD_WIDTH / MAP_TILE_SIZE;

const layerKind = z.enum([
  'deepBackdrop',
  'farGround',
  'groundBase',
  'terrainSurface',
  'terrainDetail',
  'airOccluder',
  'weather',
]);

export const TerrainCellSchema = z.object({
  x: z
    .number()
    .int()
    .min(0)
    .max(MAP_COLUMNS - 1),
  row: z.number().int().nonnegative(),
  tile: z.number().int().nonnegative(),
  /** Optional exact atlas frame for authored structures and landmark compositions. */
  frame: z.number().int().nonnegative().optional(),
  /** Optional adjacency mask generated by the Composer autotiler (Cardinal-16 or Blob-47). */
  variant: z.number().int().min(0).max(255).optional(),
});

const TerrainLayerRenderModeSchema = z.enum(['cells', 'tileSprite', 'compositedCells']);

export const TerrainLayerSchema = z
  .object({
    id: SafeIdSchema,
    name: z.string().min(1),
    kind: layerKind,
    scrollRatio: z.number().min(0.05).max(2),
    depth: z.number().int(),
    opacity: z.number().min(0).max(1).default(1),
    collisionAligned: z.boolean().default(false),
    visible: z.boolean().default(true),
    renderMode: TerrainLayerRenderModeSchema.default('cells'),
    materialTile: z.number().int().nonnegative().optional(),
    cells: z.array(TerrainCellSchema),
  })
  .superRefine((layer, ctx) => {
    if ((layer.renderMode === 'tileSprite' || layer.renderMode === 'compositedCells') && layer.materialTile === undefined) {
      ctx.addIssue({
        code: 'custom',
        path: ['materialTile'],
        message: `${layer.renderMode} layers require materialTile`,
      });
    }
    if (layer.renderMode === 'tileSprite' && layer.cells.length > 0) {
      ctx.addIssue({
        code: 'custom',
        path: ['cells'],
        message: 'tileSprite layers must not store explicit cells',
      });
    }
    if (layer.renderMode === 'compositedCells' && layer.cells.length === 0) {
      ctx.addIssue({
        code: 'custom',
        path: ['cells'],
        message: 'compositedCells layers require mask cells',
      });
    }
  });

export const TerrainMapSchema = z
  .object({
    formatVersion: z.literal('2.0'),
    id: SafeIdSchema,
    displayName: z.string().min(1),
    biomeId: SafeIdSchema,
    tileSize: z.literal(MAP_TILE_SIZE),
    worldWidth: z.literal(MAP_WORLD_WIDTH),
    rows: z.number().int().positive(),
    chunkRows: z.number().int().min(4).max(64).default(16),
    originWorldY: z.number(),
    layers: z.array(TerrainLayerSchema).min(1),
  })
  .superRefine((map, ctx) => {
    const ids = new Set<string>();
    map.layers.forEach((layer, li) => {
      if (ids.has(layer.id)) {
        ctx.addIssue({
          code: 'custom',
          path: ['layers', li, 'id'],
          message: `duplicate layer id "${layer.id}"`,
        });
      }
      ids.add(layer.id);
      if (layer.collisionAligned && layer.scrollRatio !== 1) {
        ctx.addIssue({
          code: 'custom',
          path: ['layers', li, 'scrollRatio'],
          message: 'collision-aligned layers must use scrollRatio 1',
        });
      }
      const cellKeys = new Set<string>();
      layer.cells.forEach((cell, ci) => {
        if (cell.row >= map.rows) {
          ctx.addIssue({
            code: 'custom',
            path: ['layers', li, 'cells', ci, 'row'],
            message: 'cell row exceeds map rows',
          });
        }
        const key = `${cell.x}:${cell.row}`;
        if (cellKeys.has(key)) {
          ctx.addIssue({
            code: 'custom',
            path: ['layers', li, 'cells', ci],
            message: `duplicate cell ${key}`,
          });
        }
        cellKeys.add(key);
      });
    });
  });

export const CorridorSampleSchema = z.object({
  worldY: z.number(),
  left: z.number().min(0).max(MAP_WORLD_WIDTH),
  right: z.number().min(0).max(MAP_WORLD_WIDTH),
});

export const TerrainCollisionSchema = z
  .object({
    formatVersion: z.literal('2.0'),
    id: SafeIdSchema,
    mapId: SafeIdSchema,
    contactDamage: z.number().nonnegative().default(20),
    lethalContact: z.boolean().default(false),
    corridor: z.object({
      id: SafeIdSchema,
      samples: z.array(CorridorSampleSchema).min(2),
      blocksPlayerProjectiles: z.boolean().default(true),
      blocksEnemyProjectiles: z.boolean().default(true),
    }),
  })
  .superRefine((collision, ctx) => {
    let prior = -Infinity;
    collision.corridor.samples.forEach((sample, i) => {
      if (sample.worldY <= prior) {
        ctx.addIssue({
          code: 'custom',
          path: ['corridor', 'samples', i, 'worldY'],
          message: 'samples must be strictly ordered by worldY',
        });
      }
      if (sample.right <= sample.left) {
        ctx.addIssue({
          code: 'custom',
          path: ['corridor', 'samples', i, 'right'],
          message: 'right must be greater than left',
        });
      }
      prior = sample.worldY;
    });
  });

export const RouteSetSchema = z
  .object({
    formatVersion: z.literal('2.0'),
    id: SafeIdSchema,
    mapId: SafeIdSchema,
    routes: z
      .array(
        z.object({
          id: SafeIdSchema,
          name: z.string().min(1),
          minimumRadius: z.number().positive(),
          samples: z
            .array(
              z.object({
                worldY: z.number(),
                centerX: z.number().min(0).max(MAP_WORLD_WIDTH),
                clearance: z.number().positive(),
              }),
            )
            .min(2),
        }),
      )
      .min(1),
  })
  .superRefine((routes, ctx) => {
    routes.routes.forEach((route, ri) => {
      let prior = -Infinity;
      route.samples.forEach((sample, si) => {
        if (sample.worldY <= prior) {
          ctx.addIssue({
            code: 'custom',
            path: ['routes', ri, 'samples', si, 'worldY'],
            message: 'samples must be strictly ordered by worldY',
          });
        }
        prior = sample.worldY;
      });
    });
  });

