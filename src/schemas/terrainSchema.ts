const BLOB47_MASK_KEY = /^(?:[0-9]|[1-9][0-9]|1[0-9]{2}|2[0-4][0-9]|25[0-5])$/;

function normalizeBlob47Mask(mask: number): number {
  let normalized = mask & 0x0f;
  if ((mask & 16) !== 0 && (normalized & 1) !== 0 && (normalized & 2) !== 0)
    normalized |= 16;
  if ((mask & 32) !== 0 && (normalized & 2) !== 0 && (normalized & 4) !== 0)
    normalized |= 32;
  if ((mask & 64) !== 0 && (normalized & 4) !== 0 && (normalized & 8) !== 0)
    normalized |= 64;
  if ((mask & 128) !== 0 && (normalized & 8) !== 0 && (normalized & 1) !== 0)
    normalized |= 128;
  return normalized;
}

const VALID_BLOB47_MASKS = Array.from({ length: 256 }, (_, value) =>
  normalizeBlob47Mask(value),
).filter((value, index, values) => values.indexOf(value) === index);

const TerrainMetatileFramesSchema = z.object({
  columns: z.number().int().positive(),
  rows: z.number().int().positive(),
  frames: z.array(z.number().int().nonnegative()).min(1),
});

const TerrainFrameChoiceSchema = z.union([
  z.number().int().nonnegative(),
  z.array(z.number().int().nonnegative()).min(1).max(4),
]);

const TerrainVisualMaterialSchema = z.object({
  materialId: SafeIdSchema,
  baseFrames: z.array(z.number().int().nonnegative()).min(1),
  cardinalFrames: z
    .record(z.string().regex(/^(?:[0-9]|1[0-5])$/), z.number().int().nonnegative())
    .optional(),
  blob47Frames: z
    .record(z.string().regex(BLOB47_MASK_KEY), TerrainFrameChoiceSchema)
    .optional(),
  metatileFrames: TerrainMetatileFramesSchema.optional(),
  animationFrames: z.array(z.number().int().nonnegative()).default([]),
  animationFps: z.number().positive().optional(),
  synchronizedAnimation: z.boolean().default(false),
});

const TerrainPlaneSchema = z.object({
  materialId: SafeIdSchema,
  uri: z
    .string()
    .min(1)
    .refine((value) => !value.includes('..') && !value.startsWith('/'), {
      message: 'plane URI must be a relative project asset path',
    }),
  frameWidth: z.number().int().positive(),
  frameHeight: z.number().int().positive(),
  columns: z.number().int().positive(),
  rows: z.number().int().positive(),
  animationFrames: z.array(z.number().int().nonnegative()).min(1),
  animationFps: z.number().positive().default(1),
  driftX: z.number().default(0),
  driftY: z.number().default(0),
});

const RuntimeTerrainTilesetSchema = z
  .object({
    id: SafeIdSchema,
    displayName: z.string().min(1),
    uri: z
      .string()
      .min(1)
      .refine((value) => !value.includes('..') && !value.startsWith('/'), {
        message: 'tileset URI must be a relative project asset path',
      }),
    tileSize: z.literal(MAP_TILE_SIZE),
    columns: z.number().int().positive(),
    rows: z.number().int().positive(),
    materials: z.array(TerrainVisualMaterialSchema).min(1),
    planes: z.array(TerrainPlaneSchema).default([]),
  })
  .superRefine((tileset, ctx) => {
    const frameCount = tileset.columns * tileset.rows;
    const materialIds = new Set<string>();
    tileset.materials.forEach((material, materialIndex) => {
      if (materialIds.has(material.materialId)) {
        ctx.addIssue({
          code: 'custom',
          path: ['materials', materialIndex, 'materialId'],
          message: `duplicate visual material "${material.materialId}"`,
        });
      }
      materialIds.add(material.materialId);
      const frames = [
        ...material.baseFrames,
        ...(material.animationFrames ?? []),
        ...Object.values(material.cardinalFrames ?? {}),
        ...Object.values(material.blob47Frames ?? {}).flatMap((choice) =>
          Array.isArray(choice) ? choice : [choice],
        ),
        ...(material.metatileFrames?.frames ?? []),
      ];
      frames.forEach((frame) => {
        if (frame >= frameCount) {
          ctx.addIssue({
            code: 'custom',
            path: ['materials', materialIndex],
            message: `frame ${frame} exceeds ${frameCount - 1}`,
          });
        }
      });
      if (material.cardinalFrames) {
        for (let mask = 0; mask < 16; mask += 1) {
          if (material.cardinalFrames[String(mask)] === undefined) {
            ctx.addIssue({
              code: 'custom',
              path: ['materials', materialIndex, 'cardinalFrames', String(mask)],
              message: `Cardinal-16 mapping is missing mask ${mask}`,
            });
          }
        }
      }
      if (material.metatileFrames) {
        const expected = material.metatileFrames.columns * material.metatileFrames.rows;
        if (material.metatileFrames.frames.length !== expected) {
          ctx.addIssue({
            code: 'custom',
            path: ['materials', materialIndex, 'metatileFrames', 'frames'],
            message: `metatile frame count must equal ${expected}`,
          });
        }
      }
      if (material.blob47Frames) {
        for (const mask of VALID_BLOB47_MASKS) {
          if (material.blob47Frames[String(mask)] === undefined) {
            ctx.addIssue({
              code: 'custom',
              path: ['materials', materialIndex, 'blob47Frames', String(mask)],
              message: `Blob-47 mapping is missing canonical mask ${mask}`,
            });
          }
        }
        for (const key of Object.keys(material.blob47Frames)) {
          const mask = Number(key);
          if (!VALID_BLOB47_MASKS.includes(mask)) {
            ctx.addIssue({
              code: 'custom',
              path: ['materials', materialIndex, 'blob47Frames', key],
              message: `Blob-47 mapping contains non-canonical mask ${key}`,
            });
          }
        }
      }
      if ((material.animationFrames?.length ?? 0) > 0 && !material.animationFps) {
        ctx.addIssue({
          code: 'custom',
          path: ['materials', materialIndex, 'animationFps'],
          message: 'animated visual materials require animationFps',
        });
      }
    });
    const planeMaterialIds = new Set<string>();
    tileset.planes.forEach((plane, planeIndex) => {
      if (planeMaterialIds.has(plane.materialId)) {
        ctx.addIssue({
          code: 'custom',
          path: ['planes', planeIndex, 'materialId'],
          message: `duplicate plane material "${plane.materialId}"`,
        });
      }
      planeMaterialIds.add(plane.materialId);
      const frameCount = plane.columns * plane.rows;
      plane.animationFrames.forEach((frame) => {
        if (frame >= frameCount) {
          ctx.addIssue({
            code: 'custom',
            path: ['planes', planeIndex, 'animationFrames'],
            message: `plane frame ${frame} exceeds ${frameCount - 1}`,
          });
        }
      });
    });
  });

export const BiomeSchema = z
  .object({
    formatVersion: z.literal('1.0'),
    id: SafeIdSchema,
    displayName: z.string().min(1),
    backgroundColor: z.number().int().nonnegative(),
    materials: z.array(
      z.object({
        tile: z.number().int().nonnegative(),
  /** Optional exact atlas frame for authored structures and landmark compositions. */
  frame: z.number().int().nonnegative().optional(),
        id: SafeIdSchema,
        displayName: z.string().min(1),
        color: z.number().int().nonnegative(),
        edgeColor: z.number().int().nonnegative(),
        alpha: z.number().min(0).max(1).default(1),
        animated: z.boolean().default(false),
        collisionRole: z.enum(['none', 'solid', 'hazard']).default('none'),
      }),
    ),
    tileset: RuntimeTerrainTilesetSchema.optional(),
  })
  .superRefine((biome, ctx) => {
    const materialIds = new Set(biome.materials.map((material) => material.id));
    biome.tileset?.materials.forEach((visual, index) => {
      if (!materialIds.has(visual.materialId)) {
        ctx.addIssue({
          code: 'custom',
          path: ['tileset', 'materials', index, 'materialId'],
          message: `visual material "${visual.materialId}" is not declared by the biome`,
        });
      }
    });
    biome.tileset?.planes.forEach((plane, index) => {
      if (!materialIds.has(plane.materialId)) {
        ctx.addIssue({
          code: 'custom',
          path: ['tileset', 'planes', index, 'materialId'],
          message: `plane material "${plane.materialId}" is not declared by the biome`,
        });
      }
    });
  });

